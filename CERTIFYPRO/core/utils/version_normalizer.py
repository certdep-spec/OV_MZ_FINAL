"""
Утиліти для нормалізації версій складу продукції.
Запобігають помилкам через різницю кириличних та латинських символів.
"""

# Мапа заміни кириличних символів на латинські аналоги для нормалізації версій
CYRILLIC_TO_LATIN = {
    "А": "A", "В": "B", "С": "C", "Е": "E", "Н": "H", "К": "K",
    "М": "M", "О": "O", "Р": "P", "Т": "T", "У": "Y", "Х": "X",
    "а": "a", "в": "b", "с": "c", "е": "e", "н": "h", "к": "k",
    "м": "m", "о": "o", "р": "p", "т": "t", "у": "y", "х": "x",
}

def normalize_version(v: str) -> str:
    """
    Нормалізує версію: strip, upper та заміна кирилиці на латиницю.
    Робить літери А, В, С тощо однаковими незалежно від розкладки клавіатури.
    """
    if not v:
        return ""
    v = str(v).strip().upper()
    return "".join(CYRILLIC_TO_LATIN.get(c, c) for c in v)
